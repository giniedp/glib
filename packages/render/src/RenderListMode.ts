import { brand, Brand } from '@gglib/utils'

export type RenderSortPriority = Brand<string, 'RenderSortPriority'>
export const RenderSortPriority = {
  State: brand<RenderSortPriority>('state'),
  Depth: brand<RenderSortPriority>('depth'),
}

export type RenderItemFlags = Brand<number, 'RenderItemFlags'>
export const RenderItemFlags = {
  Opaque: brand<RenderItemFlags>(1 << 0),
  Transparent: brand<RenderItemFlags>(1 << 1),
  ShadowCaster: brand<RenderItemFlags>(1 << 2),
  Overlay: brand<RenderItemFlags>(1 << 3),
}

export type RenderFilter = {
  includeMask: RenderItemFlags
  excludeMask: RenderItemFlags
}

export const RenderFilter = {
  Opaque: {
    includeMask: RenderItemFlags.Opaque,
    excludeMask: brand<RenderItemFlags>(0),
  } satisfies RenderFilter,
  Transparent: {
    includeMask: RenderItemFlags.Transparent,
    excludeMask: brand<RenderItemFlags>(0),
  } satisfies RenderFilter,
  ShadowCaster: {
    includeMask: RenderItemFlags.ShadowCaster,
    excludeMask: brand<RenderItemFlags>(0),
  } satisfies RenderFilter,
  Overlay: {
    includeMask: RenderItemFlags.Overlay,
    excludeMask: brand<RenderItemFlags>(0),
  } satisfies RenderFilter,
}

/**
 * An object holding common components that are used to create a sort key for a render item.
 * Each component contributes to a part of the sort key. The actual key is generated by the {@link RenderListMode.getKey} function,
 * which packs these components into a {@link SortKey}.
 */
export interface Sortable {
  /**
   * The layer component. Can be a layer ID or a combination of application-specific flags.
   */
  layer: number
  /**
   * The render state ID that corresponds to a pipeline state e.g. blend state.
   */
  state: number
  /**
   * The depth component, usually the distance from the camera to the item in view space.
   */
  depth: number
  /**
   * The material ID
   */
  material: number
  /**
   * The material ID
   */
  geometry: number
}

/**
 * A sort key made of two integers, compared by `hi` first and `lo` second.
 *
 * @remarks
 * Each part holds an integer up to 2^53, so keys can be built and compared without allocations (unlike bigint).
 */
export interface SortKey {
  hi: number
  lo: number
}

/**
 * Compares two sort keys
 */
export function compareSortKey(aHi: number, aLo: number, bHi: number, bLo: number): number {
  if (aHi !== bHi) {
    return aHi < bHi ? -1 : 1
  }
  if (aLo !== bLo) {
    return aLo < bLo ? -1 : 1
  }
  return 0
}

/**
 * Defines the sorting andfilter behavior for render items in a render pass.
 */
export class RenderListMode {
  public static Opaque = new RenderListMode(RenderSortPriority.State, RenderItemFlags.Opaque)
  public static Transparent = new RenderListMode(RenderSortPriority.Depth, RenderItemFlags.Transparent)
  public static Shadow = new RenderListMode(RenderSortPriority.State, RenderItemFlags.ShadowCaster)

  public readonly mask: RenderItemFlags
  public readonly priority: RenderSortPriority

  public constructor(priority: RenderSortPriority, mask: RenderItemFlags) {
    this.mask = mask
    this.priority = priority
    this.getKey = this.buildKeyFn(mask, priority)
  }

  /**
   * Generates a sort key for a given render item based on the components defined in the item and the sorting behavior of this mode.
   * @param item
   * @returns
   */
  public getKey(item: Sortable, out: SortKey): SortKey {
    out.hi = 0
    out.lo = 0
    return out
  }

  protected buildKeyFn(mask: RenderItemFlags, priority: RenderSortPriority): (item: Sortable, out: SortKey) => SortKey {
    if (mask & RenderItemFlags.Transparent) {
      return priority === RenderSortPriority.Depth ? sortTransparentBackToFront : sortStateFirst
    }
    return priority === RenderSortPriority.Depth ? sortOpaqueFrontToBack : sortStateFirst
  }
}

// ---------- Sort key implementations ----------
// Fields are combined with multiplication instead of bit shifts, so each part can use up to 53 bits.
// Values that exceed their field width wrap around, which only affects the order, not correctness.

const P8 = 2 ** 8
const P20 = 2 ** 20
const P25 = 2 ** 25
const P26 = 2 ** 26
const P32 = 2 ** 32
const P33 = 2 ** 33
const DEPTH_26 = P26 - 1

function sortStateFirst(item: Sortable, out: SortKey): SortKey {
  // hi: [ layer (21) | state (32) ]
  // lo: [ material (20) | geometry (25) | depth (8) ]
  const depthBits = (item.depth * 255) | 0 // low-resolution depth
  out.hi = (item.layer % 2 ** 21) * P32 + (item.state >>> 0)
  out.lo = (item.material % P20) * P33 + (item.geometry % P25) * P8 + depthBits
  return out
}

function sortOpaqueFrontToBack(item: Sortable, out: SortKey): SortKey {
  // hi: [ layer (27) | depth (26) ]
  // lo: [ state (32) | material (10) | geometry (10) ]
  const depthBits = Math.min((item.depth * DEPTH_26) | 0, DEPTH_26)
  out.hi = (item.layer % 2 ** 27) * P26 + depthBits
  out.lo = (item.state >>> 0) * P20 + (item.material % 1024) * 1024 + (item.geometry % 1024)
  return out
}

function sortTransparentBackToFront(item: Sortable, out: SortKey): SortKey {
  // hi: [ layer (27) | reverse depth (26) ]
  // lo: [ state (32) | material (10) | geometry (10) ]
  const depthBits = DEPTH_26 - Math.min((item.depth * DEPTH_26) | 0, DEPTH_26)
  out.hi = (item.layer % 2 ** 27) * P26 + depthBits
  out.lo = (item.state >>> 0) * P20 + (item.material % 1024) * 1024 + (item.geometry % 1024)
  return out
}
